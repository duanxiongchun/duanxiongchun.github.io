// ==================== 🧮 维度2：数字规律（动态生成算法）====================

function getDynamicNumeric(qIdx, type) {
  if (type === 1) {
    const d = (qIdx % 3) + 2, s = qIdx + 1, pos = qIdx % 4;
    const seq = [s, s+d, s+d*2, s+d*3, s+d*4];
    const ans = seq[pos]; seq[pos] = null;
    return { seq, ans, hint: `每次加 ${d}，看看缺什么？`, title: '数列加法规律' };
  }
  if (type === 2) {
    const d = (qIdx % 3) + 2, s = 25 - qIdx, pos = qIdx % 4;
    const seq = [s, s-d, s-d*2, s-d*3, s-d*4];
    const ans = seq[pos]; seq[pos] = null;
    return { seq, ans, hint: `每次减 ${d}，数字在变小。`, title: '数列减法规律' };
  }
  if (type === 3) {
    const A = qIdx + 3, B = qIdx + 2, C = qIdx + 1;
    const ans = A + B - C;
    return { left: [A, B], right: [C, null], ans, hint: `左边 ${A}+${B}=${A+B}，右边 ${C}+？也是 ${A+B} 呢？` };
  }
  if (type === 4) {
    const emojis = ['🍎','🍌','🍒','🍓','🍇','🍊','🍉','🍍','🍑','🍋'];
    const emoji = emojis[qIdx];
    const ans = qIdx + 2;
    return { expr1: `${emoji} + ${emoji} = ${ans + ans}`, q: `${emoji} 应该是多少？`, ans, hint: `两个一样的${emoji}相加是 ${ans + ans}，一个是得多少？` };
  }
  // type 5: 金字塔
  const A = qIdx + 1, B = qIdx + 2, C = qIdx + 1;
  const D = A + B, E = B + C, topVal = D + E;
  return { bottom: [A, B, C], middle: [D, E], top: null, ans: topVal, hint: `下面两个相邻相加等于上层格数：${D}+${E} 是多少？` };
}

